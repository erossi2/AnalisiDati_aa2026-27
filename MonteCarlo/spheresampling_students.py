def sphere_reject(n, rng):
    '''Rejection sampling. Returns (points of shape (n, 3), acceptance fraction).'''
    chunks, n_have, n_tried = [], 0, 0
    while n_have < n:
        v  = rng.uniform(-1, 1, (2 * n, 3))      # points in the cube
