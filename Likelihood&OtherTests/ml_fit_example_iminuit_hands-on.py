    rng = np.random.default_rng(2025)
    a_true, b_true = 0.35, 0.25

    def pdf_unnormalized(x, a, b):
        return 1.0 + a*x + b*x**2

    # Rejection sampling. The envelope is evaluated on a dense grid.
    grid = np.linspace(XMIN, XMAX, 2000)
    envelope = pdf_unnormalized(grid, a_true, b_true).max()
    accepted = []
    while len(accepted) < 1000:
        candidates = rng.uniform(XMIN, XMAX, 3000)
        keep = rng.uniform(0, envelope, candidates.size) < pdf_unnormalized(
            candidates, a_true, b_true
        )
        accepted.extend(candidates[keep].tolist())
    data = np.asarray(accepted[:1000])
    data_source = "toy sample (a=0.35, b=0.25)"

